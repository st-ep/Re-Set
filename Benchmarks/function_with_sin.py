"""
Benchmark: Learning f(x) = a*sin(x) + b*x^2 + c*x + d with SetONet
--------------------------------------------------------------------
This benchmark focuses on learning the function f(x) itself from
samples of f(x_i). The function space is defined by
f(x) = a*sin(x) + b*x^2 + c*x + d, where a, b, c, d are random.

branch input     : {(x_i , f(x_i))}_i      ➜ coefficients  (B , p , 1)
trunk  input     : {y_j}_j                  ➜ basis values  (B , n_y , p , 1)
prediction       :  Σ_p  coeff_p · basis_p  ≈ f(y)

The data is generated by `generate_batch_sin`.
"""

from Benchmarks.setonet_1d_benchmark import run_setonet_benchmark

# --------------------------------------------------------------------------- #
# Main experiment
# --------------------------------------------------------------------------- #
def main() -> None:
    cfg = dict(
        task_type   = "input_function_sin", # Key for the new task

        # Experiment set-up (can be adjusted as needed)
        input_range = [-3.0, 3.0], # Sin function might benefit from a wider range
        scale       = 0.5,         # Scale for coefficients a, b, c, d
        n_sensor_points = 100,     # Number of sensor points (where f(x_i) is sampled)
        n_trunk_points  = 100,     # Number of points to evaluate the learned function
        latent_p        = 32,      # Latent dimension for SetONet
        n_samples_to_plot = 3,
        batch_size      = 256,
        n_epochs        = 50_000,  # Increased epochs slightly
        print_interval  = 500,

        # Optimisation
        lr                = 1e-3,
        lr_schedule_steps = [450000, 800000], # Adjusted schedule
        lr_schedule_gamma = 0.5,
        l1_lambda         = 2e-5, # Adjusted L1

        # Model hyper-params (can be tuned for the new task)
        phi_hidden_size   = 256,
        rho_hidden_size   = 256,
        trunk_hidden_size = 256,
        n_trunk_layers    = 4,
        phi_output_size   = 32,    # Should match latent_p
        aggregation_type  = "attention", # or "mean", "sum"
        attention_n_tokens= 1,
        pos_encoding_type = "skip",  # or "learnable", "none"
        use_deeponet_bias = True,
        # For this task, we are not providing sensor derivatives as input to the branch net
        concat_sensor_derivative_to_branch_input = False,
    )

    run_setonet_benchmark(cfg)

# --------------------------------------------------------------------------- #
if __name__ == "__main__":
    main() 