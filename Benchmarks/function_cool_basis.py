"""
Benchmark: Learning f(x) = a*g1(x) + b*g2(x) + c*g3(x) + d*g4(x) with SetONet
---------------------------------------------------------------------------------
This benchmark focuses on learning a function f(x) itself from
samples of f(x_i). The function space is defined by a linear combination
of "cool-looking" basis functions g_i(x), where coefficients a, b, c, d are random.

branch input     : {(x_i , f(x_i))}_i      ➜ coefficients  (B , p , 1)
trunk  input     : {y_j}_j                  ➜ basis values  (B , n_y , p , 1)
prediction       :  Σ_p  coeff_p · basis_p  ≈ f(y)

The data is generated by `generate_batch_cool_basis`.
"""

from Benchmarks.setonet_1d_benchmark import run_setonet_benchmark

# --------------------------------------------------------------------------- #
# Main experiment
# --------------------------------------------------------------------------- #
def main() -> None:
    cfg = dict(
        task_type   = "input_function_cool_basis", # Key for the new task

        # Experiment set-up (can be adjusted as needed for complex functions)
        input_range = [-1.5, 1.5], # Wider range to see more of the basis functions
        scale       = 0.3,         # Scale for coefficients a, b, c, d
        n_sensor_points = 200,     # Number of sensor points
        n_trunk_points  = 100,     # Number of points to evaluate the learned function
        latent_p        = 16,      # Increased latent dimension for more complex functions
        n_samples_to_plot = 4,
        batch_size      = 128,     # Potentially smaller batch size if memory is an issue
        n_epochs        = 80_000,  # Increased epochs
        print_interval  = 500,

        # Optimisation
        lr                = 1e-3,
        lr_schedule_steps = [500000, 1000000], 
        lr_schedule_gamma = 0.5,
        l1_lambda         = 3.0e-5, 

        # Model hyper-params
        phi_hidden_size   = 256, # Increased hidden sizes
        rho_hidden_size   = 256,
        trunk_hidden_size = 256,
        n_trunk_layers    = 4,     # Deeper trunk
        phi_output_size   = 32,    # Should match latent_p
        aggregation_type  = "attention", 
        attention_n_tokens= 4,     # Potentially more attention tokens
        pos_encoding_type = "skip",
        use_deeponet_bias = True,
        concat_sensor_derivative_to_branch_input = False, # No derivatives in this task
    )

    run_setonet_benchmark(cfg)

# --------------------------------------------------------------------------- #
if __name__ == "__main__":
    main() 